GLYPHS: dict[str, tuple[str, ...]] = {ch: tuple(rows.split("/")) for ch, rows in _G.items()}
for _ch, _rows in GLYPHS.items():  # the asset is validated at import, once
    if len(_rows) != CELL_H or any(len(r) != CELL_W for r in _rows):
        raise ValueError(f"malformed glyph in font asset: {_ch!r}")

#: Substituted for any character the asset does not carry.
MISSING = tuple(["11111"] + ["10001"] * 5 + ["11111"])


@dataclass(frozen=True)
class FontAsset:
    """A preprocessed font, addressed by ``font_id`` exactly as on the device."""

    font_id: str
    family: str
    size: int

    @property
    def scale(self) -> float:
        return self.size / CELL_H

    def cells(self, text: str) -> list[tuple[int, int, int]]:
        """Set pixels as (glyph_index, column, row) in cell units."""
        out = []
        for index, ch in enumerate(text):
            rows = GLYPHS.get(ch, MISSING)
            for row, bits in enumerate(rows):
                for col, bit in enumerate(bits):
                    if bit == "1":
                        out.append((index, col, row))
        return out

    def extent(self, text: str) -> tuple[float, float]:
        """(width, height) in device units, advance-based."""
        if not text:
            return (0.0, self.size)
        return ((len(text) * ADVANCE - 1) * self.scale, float(self.size))


def resolve_font(font_id: str) -> FontAsset:
    """Resolve a ``font_id`` such as ``mementum-sans-24`` to a font asset.

    A node that cannot resolve a font must fail visibly rather than silently
    substitute one (proposal §18), so this raises instead of guessing.
    """
    family, _, size = font_id.rpartition("-")
    if not family or not size.isdigit():
        raise ValueError(f"unresolvable font_id: {font_id!r} (expected <family>-<px>)")
    return FontAsset(font_id=font_id, family=family, size=int(size))


def text_extent(font_id: str, text: str) -> tuple[float, float]:
    return resolve_font(font_id).extent(text)
